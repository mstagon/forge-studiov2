#!/usr/bin/env node
// build-gauntlet-action.mjs — gauntlet-action.ts 를 단일 .mjs 로 번들.
// 산출물은 harness-template/.github/ 에 커밋되어 워크스페이스로 ship 된다.
// CI 에서 `node .github/forge-gauntlet.mjs` 로 forge-cli 없이 실행.
import { build } from 'esbuild'
import path from 'path'
import { fileURLToPath } from 'url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const outfile = path.join(root, 'resources', 'harness-template', '.github', 'forge-gauntlet.mjs')

await build({
  entryPoints: [path.join(root, 'electron', 'services', 'gauntlet-action.ts')],
  outfile,
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node20',
  // Node 내장 모듈만 사용 (child_process/fs/path/util) — external 불필요.
  banner: { js: '// GENERATED by scripts/build-gauntlet-action.mjs — do not edit. Source: electron/services/gauntlet-action.ts' },
})

console.log(`✅ forge-gauntlet.mjs 번들 완료: ${path.relative(root, outfile)}`)
